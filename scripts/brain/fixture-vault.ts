// `pnpm run brain:fixture-vault [dir]` (#112): materialize the synthetic parser fixtures
// (evals/brain/parser/*.md.fixture, listed in manifest.json) byte-for-byte as a real vault of
// .md files, for ingestion tests and local demos. Default target: evals/brain/vault
// (git-ignored). The fixtures themselves are never modified.
import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, isAbsolute, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { z } from 'zod';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const fixtures = join(repo, 'evals/brain/parser');
// Written into every materialized vault; only a directory carrying it is ever cleared.
const MARKER = '.aetherion-fixture-vault';

const manifestSchema = z.object({
  schemaVersion: z.literal(1),
  notes: z.array(
    z.object({
      path: z
        .string()
        .refine(
          (p) => !isAbsolute(p) && !p.includes('\\') && p.split('/').every((s) => s && s !== '..'),
          'unsafe fixture path',
        ),
    }),
  ),
});

const sha256 = (bytes: Buffer) => createHash('sha256').update(bytes).digest('hex');

export const materializeFixtureVault = async (target: string): Promise<number> => {
  const destination = resolve(target);
  const inside = relative(fixtures, destination);
  if (!inside.startsWith('..') && !isAbsolute(inside))
    throw new Error('refusing to write inside evals/brain/parser');
  if (existsSync(destination)) {
    const entries = await readdir(destination);
    if (entries.length && !entries.includes(MARKER))
      throw new Error(`refusing to clear ${destination}: not a materialized fixture vault`);
    await rm(destination, { recursive: true, force: true });
  }
  await mkdir(destination, { recursive: true });
  const manifest = manifestSchema.parse(
    JSON.parse(await readFile(join(fixtures, 'manifest.json'), 'utf8')) as unknown,
  );
  for (const note of manifest.notes) {
    const bytes = await readFile(join(fixtures, `${note.path}.fixture`));
    const out = join(destination, note.path);
    await mkdir(dirname(out), { recursive: true });
    await writeFile(out, bytes);
    if (sha256(await readFile(out)) !== sha256(bytes))
      throw new Error(`byte mismatch: ${note.path}`);
  }
  await writeFile(
    join(destination, MARKER),
    'Generated by pnpm run brain:fixture-vault; safe to delete.\n',
  );
  return manifest.notes.length;
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = process.argv[2] ?? join(repo, 'evals/brain/vault');
  try {
    const count = await materializeFixtureVault(target);
    console.log(`materialized ${count} fixture notes into ${resolve(target)}`);
  } catch (error) {
    console.error((error as Error).message);
    process.exitCode = 1;
  }
}
